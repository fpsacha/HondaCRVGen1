--[[
Honda CR-V (RD1), function feature, client UI:
  * right-click on the car (outside): "Lift the cargo floor" until the under-floor storage is found
    (timed action ISCRVFunctionLiftFloor; the state changes in its complete(), on the server), and the same on the
    outside radial menu (V, and Project Viewpoint's quick-interact list);
  * right-click on the owner's manual: "Browse the owner's manual" opens its designed pages in the print media window (text only, nothing
    changes; reading it the vanilla way teaches it, and opens the same window).
  * the manual is three spreads (F.MANUAL_SPREADS). Vanilla's print media window shows one page, so the manual's window
    is a template derived from it with two more buttons on its bottom bar, previous and next spread: a button
    closes the window and opens the neighbouring spread where it was. When the template cannot be derived (a
    changed game), the plain window opens the first spread.
  * the spreads' words are the player's language (H-SAVES-I5): the art ships without them and every string is laid
    over it when a spread opens, as vanilla's B42 newspapers lay their text (text elements in the print media data
    string, drawn by AtomUIText with the game's SDF fonts). HondaCRVGen1_ManualLayout.lua (generated by
    scripts/manual_art.py) gives each string its box: where it starts, its font, size, colour, angle, its width and
    the room the English took. M.manualWords lays out getText(M.MANUAL_KEY_PREFIX .. id) in that box with the game's
    font metrics (TextManager.MeasureStringX): **runs** bold, wrapped to the box's width, shrunk to fit its room
    (to M.MIN_FIT, then it may run long). A string the SDF fonts have no glyphs for (CJK, Thai...) uses the
    language's own UI font (M.FALLBACK_FONT). Lines break at spaces, and between any two CJK characters (Chinese and
    Japanese have no spaces), never before a closing mark (，。、）」 ...) nor after an opening one.
]]

