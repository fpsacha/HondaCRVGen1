def sandbox_section():
    """media/sandbox-options.txt for the features' SANDBOX options (CustomSandboxOptions reads
    <mod>/42/media/sandbox-options.txt: VERSION, option <page>.<name> { type, min, max, default,
    numValues, page, translation, valueTranslation }); SandboxVars.HondaCRVGen1.<name> in Lua.
    None when there are none."""
    opts = features.sandbox()
    if not opts:
        return None
    out = ["VERSION = 1,", ""]
    for o in opts:
        lines = ["option %s.%s" % (SANDBOX_PAGE, o["name"]), "{", "\ttype = %s," % o["type"]]
        if o["type"] in ("integer", "double"):
            lines += ["\tmin = %s," % o["min"], "\tmax = %s," % o["max"]]
        if o["type"] == "enum":
            lines.append("\tnumValues = %d," % len(o["values"]))
        lines += ["\tdefault = %s," % _value(o["default"]), "\tpage = %s," % SANDBOX_PAGE,
                  "\ttranslation = %s_%s," % (SANDBOX_PAGE, o["name"])]
        if o["type"] == "enum":
            lines.append("\tvalueTranslation = %s_%s," % (SANDBOX_PAGE, o["name"]))
        lines += ["}", ""]
        out += lines
    return "\n".join(out)


