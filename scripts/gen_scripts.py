def _write_or_remove(path, text):
    """Write a generated file, or remove it once nothing generates it."""
    if text is None:
        if os.path.exists(path):
            os.remove(path)
            print("REMOVED %s (no feature writes it any more)" % path)
        return None
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("WROTE %s" % path)
    return path


def copy_feature_files(mod42):
    """The features' tracked files (LUA, MEDIA) from this checkout's mod folder into the one mod42 sits in
    when that is another tree (a CRV_ROOT test build, --out: <out>/media and <out>/../common/media); a
    declared file that is missing stops the build."""
    src_mod, dst_mod = os.path.dirname(CHECKOUT_MOD42), os.path.dirname(mod42)
    copied = []
    for feat, rel in features.media():
        parts = rel.split("/")
        src = os.path.join(src_mod, *parts)
        if not os.path.exists(src):
            raise SystemExit("gen_scripts: feature %s declares %s, which is not in %s" % (feat, rel, src_mod))
        # --out DIR stands for the 42/ folder: 42/... goes under DIR, common/... beside it
        dst = os.path.join(mod42, *parts[1:]) if parts[0] == "42" else os.path.join(dst_mod, *parts)
        if os.path.normcase(os.path.abspath(src)) != os.path.normcase(os.path.abspath(dst)):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(src, dst)
            copied.append(dst)
            print("COPIED %s" % dst)
    return copied


