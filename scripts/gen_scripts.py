def _acc_model_name(geo):
    return "%sAcc_%s" % (VEHICLE, geo[len("acc_"):])


def _gen():
    """This module, for the feature callables (gen)."""
    return sys.modules[__name__]


def _model(name, sub, static=True, bone=None, texture=None, shader=None):
    """bone: the bone, or the bones in order, this model script weights. ModelScript.Load turns every
    `boneWeight` line into one AnimBoneWeight of the same mask: the mask of the track the model's
    part plays, which must cover every bone a child part's model rides."""
    lines = ["\tmodel %s" % name, "\t{",
             "\t\tmesh = %s|%s," % (FBX, sub),
             "\t\tshader = %s," % (shader or SHADER),
             "\t\tinvertX = FALSE,"]
    if texture:
        lines.append("\t\ttexture = %s," % texture)
    if not static:
        lines.append("\t\tstatic = FALSE,")
    lines.append("\t\tscale = %s," % SCALE)
    for b in ([bone] if isinstance(bone, str) else (bone or [])):
        lines.append("\t\tboneWeight = %s 1.0," % b)
    lines += ["\t}", ""]
    return "\n".join(lines)


def _anim_block(indent, clip, close_rate=1.5, open_rate=1.0):
    t = "\t" * indent
    return "\n".join([
        "%sanim Close" % t, "%s{" % t,
        "%s\tanim = %s," % (t, clip), "%s\treverse = TRUE," % t,
        "%s\trate = %s," % (t, close_rate), "%s}" % t,
        "%sanim Open" % t, "%s{" % t,
        "%s\tanim = %s," % (t, clip), "%s\trate = %s," % (t, open_rate), "%s}" % t,
        "%sanim Closed" % t, "%s{" % t,
        "%s\tanim = %s," % (t, clip), "%s\tanimate = FALSE," % t, "%s}" % t,
        "%sanim Opened" % t, "%s{" % t,
        "%s\tanim = %s," % (t, clip), "%s\treverse = TRUE," % t,
        "%s\tanimate = FALSE," % t, "%s}" % t,
    ])


