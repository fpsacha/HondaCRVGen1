# Translator.getTextInternal (42.21 bytecode) picks ONE map by the key's prefix and has no fallback (a miss
# returns the key itself); each map is filled only from the file of its name (Translator$1 BY_NAME). The
# prefixes this mod uses, in the order the game tests them ("UI_" first, so "IGUI_" is not caught by it).
TRANSLATION_ROUTES = [("UI_", "UI"), ("IGUI_", "IG_UI"), ("ContextMenu_", "ContextMenu"), ("Sandbox_", "Sandbox"),
                      ("Tooltip_", "Tooltip")]


def translation_file(key):
    """The Translate/EN/<file>.json the game reads a prefixed key from (None: not routed by prefix,
    e.g. item names Base.X and recipe names)."""
    for prefix, fname in TRANSLATION_ROUTES:
        if key.startswith(prefix):
            return fname
    return None


