r"""
Generate the Project Zomboid B42 vehicle scripts for the CR-V.

    python scripts/gen_scripts.py

Written rather than hand-maintained because the four doors and four windows are the same block
with the side swapped, and every model name has to agree with an FBX sub-object name exactly.

Structure follows KI5 (spec/pz-conventions.md section 7) but uses only what the base game ships:
the shader is vanilla `vehicle_multiuv`, not KI5's `damn_vehicle_shader`, which lives in their
damnlib mod. Mechanical parts come from the vanilla SUV template (`template! = SUV`); the parts
that need a mesh and a clip are overridden here.

Units: script space is roughly real metres horizontally and about 0.72-0.75 of real vertically.

Part models and animation, read from the B42 bytecode (2026-10-12, javap notes in the scratch
partmodels/ dir): a part's clip plays on its FIRST model only (BaseVehicle.playPartAnim ->
getModelInfoForPart), masked by that model script's `boneWeight` lines (ModelScript.Load accumulates
them; no line = every bone, AnimationTrack.getBoneWeight returns 1 without a mask). A child part
(`parent =`) is DRAWN by the parent's AnimationPlayer (ModelInfo.getAnimationPlayer delegates to the
parent's first model) with its bones mapped by name, so a child's bones must be weighted on the
parent's track, or get their own track from the child's own anim, as the windows do. A second model
on the SAME part gets its own player and never a track: extra MOVING meshes are child parts, extra
STATIC meshes are additional `model` blocks toggled with part:setModelVisible (the roof rack's cargo).
Every ModelInfo sharing a player calls AnimationPlayer.Update once per frame, so a part's anim rates
are divided by the number of sharers (KI5's Bronco gate runs at 0.5 with its rear glass parented).
Model visibility is neither saved nor synced, and the `update` lua hook never runs on MP clients.

Feature plugins (scripts/features, spec/feature-plugins.md): every active feature module's MODELS,
VEHICLE_PARTS (in every CR-V vehicle script), VEHICLE_SCRIPTS (whole second scripts, one file each),
ITEMS, RECIPES, TRANSLATIONS, SANDBOX and DISTRIBUTIONS land in the generated files, and its LUA and
MEDIA files (tracked in this checkout's mod folder) are copied into a CRV_ROOT test build. Callables get this module as `gen` and may use its helpers:
model_block, acc_model_name, tool_table, accessory_part, vehicle_section, vehicle_script, tuning_with
and the constants (VEHICLE, FBX, TEX, SHADER, SCALE, DOORS, DOOR_PARTS, WHEELS, TUNING...). With no
feature module the output is byte-identical to the build before the plugins (scripts/test_features.py).
"""
