def loot_lua():
    """server/Items/HondaCRVGen1_Loot.lua: the features' DISTRIBUTIONS added to the vanilla procedural
    lists before the game merges them (OnPreDistributionMerge); a named sandbox option (a double)
    multiplies the weight. None when there are none."""
    entries = features.distributions()
    if not entries:
        return None
    rows = []
    for e in entries:
        sb = (', sandbox = "%s"' % e["sandbox"]) if e.get("sandbox") else ""
        rows.append('    { list = "%s", item = "%s", weight = %s%s },   -- %s' % (e["list"], e["item"], e["weight"], sb, e["feature"]))
    rarity = [o for o in features.sandbox() if o["name"] == LOOT_RARITY]
    if rarity:
        return _loot_lua_rarity(rows, rarity[0])
    return "\n".join([
        "-- " + GENERATED,
        "-- Procedural loot for the CR-V features' items (ProceduralDistributions.list.<list>.items: item, weight).",
        'require "Items/ProceduralDistributions"',
        "",
        "local LOOT = {"] + rows + [
        "}",
        "",
        "local function add()",
        "    local lists = ProceduralDistributions and ProceduralDistributions.list",
        "    if not lists then return end",
        "    local vars = SandboxVars and SandboxVars.%s" % SANDBOX_PAGE,
        "    for _, e in ipairs(LOOT) do",
        "        local l = lists[e.list]",
        "        local w = e.weight",
        "        if e.sandbox and vars and type(vars[e.sandbox]) == \"number\" then w = w * vars[e.sandbox] end",
        "        if l and l.items and w > 0 then",
        "            table.insert(l.items, e.item)",
        "            table.insert(l.items, w)",
        "        end",
        "    end",
        "end",
        "",
        "Events.OnPreDistributionMerge.Add(add)",
        ""])


# function feature (2026-10-13): the loot rarity slider. A sandbox option of this name (declared by the
# function feature, a double 0..max) scales EVERY feature's loot entry. Loot weights are read by
# ItemPickerJava.Parse right after SandboxOptions.load with no Lua event in between, so the
# OnPreDistributionMerge add() sees the sandbox's defaults, not the server's values (IsoWorld.init order,
# 42.21). Instead each entry goes in at weight x max (the headroom) and OnFillContainer, which fires after
# every procedural fill on the side that fills (single player, the server), keeps each of our items it
# finds with probability rarity x entry option / max. An item's roll chance is linear in its weight
# (ItemPickerJava.getActualSpawnChance: weight x loot modifiers x 100 against Rand(10000)), so the
# expected count is weight x rarity as long as weight x max stays far from the 100 % cap.
LOOT_RARITY = "FunctionLootRarity"


def _loot_lua_rarity(rows, opt):
    head = float(opt.get("max") or 1.0)
    return "\n".join([
        "-- " + GENERATED,
        "-- Procedural loot for the CR-V features' items (ProceduralDistributions.list.<list>.items: item, weight),",
        "-- scaled by SandboxVars.%s.%s (see gen_scripts.LOOT_RARITY): inserted at weight x HEADROOM," % (SANDBOX_PAGE, LOOT_RARITY),
        "-- thinned when a container is filled (OnFillContainer) to rarity x entry option / HEADROOM.",
        'require "Items/ProceduralDistributions"',
        "",
        "local LOOT = {"] + rows + [
        "}",
        "local HEADROOM = %r" % head,
        "",
        "HondaCRVGen1 = HondaCRVGen1 or {}",
        "local Loot = {}",
        "HondaCRVGen1.Loot = Loot",
        "Loot.LOOT = LOOT",
        "Loot.HEADROOM = HEADROOM",
        "",
        "-- item full type -> the entry option that scales it (false: none); the first entry naming an item decides",
        "Loot.option = {}",
        "for _, e in ipairs(LOOT) do",
        "    if Loot.option[e.item] == nil then Loot.option[e.item] = e.sandbox or false end",
        "end",
        "",
        "local function number(name, default)",
        "    local vars = SandboxVars and SandboxVars.%s" % SANDBOX_PAGE,
        "    local v = vars and vars[name]",
        "    if type(v) ~= \"number\" or v < 0 then return default end",
        "    return v",
        "end",
        "",
        "-- probability that one rolled copy of item stays in the container",
        "function Loot.keep(item)",
        "    local opt = Loot.option[item]",
        "    if opt == nil then return 1 end",
        "    local k = number(\"%s\", 1.0)" % LOOT_RARITY,
        "    if opt then k = k * number(opt, 1.0) end",
        "    return math.min(1, k / HEADROOM)",
        "end",
        "",
        "function Loot.add()",
        "    local lists = ProceduralDistributions and ProceduralDistributions.list",
        "    if not lists then return end",
        "    for _, e in ipairs(LOOT) do",
        "        local l = lists[e.list]",
        "        local w = e.weight * HEADROOM",
        "        if l and l.items and w > 0 then",
        "            table.insert(l.items, e.item)",
        "            table.insert(l.items, w)",
        "        end",
        "    end",
        "end",
        "",
        "-- OnFillContainer(roomName, containerType, container): drop the share of our items the slider takes away",
        "function Loot.thin(roomName, containerType, container)",
        "    if isClient() or not container then return 0 end",
        "    local items = container:getItems()",
        "    if not items then return 0 end",
        "    local drop = {}",
        "    for i = 0, items:size() - 1 do",
        "        local it = items:get(i)",
        "        local keep = Loot.option[it:getFullType()] ~= nil and Loot.keep(it:getFullType()) or 1",
        "        if keep < 1 and ZombRandFloat(0, 1) >= keep then drop[#drop + 1] = it end",
        "    end",
        "    for _, it in ipairs(drop) do container:Remove(it) end",
        "    return #drop",
        "end",
        "",
        "Events.OnPreDistributionMerge.Add(Loot.add)",
        "Events.OnFillContainer.Add(Loot.thin)",
        ""])


