r"""
Generate the mod's vehicle shader set from the game's own vehicle_multiuv sources.

    python scripts\gen_shaders.py

Provenance: every line that is not marked below comes from The Indie Stone's shipped shaders
(media/shaders/vehicle_norandom_multiuv.frag, vehicle_multiuv_static.vert, vehicle_multiuv_noreflect.vert).
Nothing is taken from other mods. The generated files are for use inside a Project Zomboid mod.

The fragment program is the game's NORANDOM variant (2026-10-13, polish feature): it differs from
vehicle_multiuv.frag only in taking the damage paint hue from the skin's own texel
(`paintColor = rgb2hsv(tex.rgb)`) instead of the car's random colour (TexturePainColor), and in
dropping the random-colour tint of texels with alpha < 1 (every CR-V skin is opaque RGB, so that tint
never applied). So a dent shades in the panel's own colour on every skin, with no per-car state that
the network could reset, and Project Viewpoint (which picks its shading kind from the shader NAME:
"norandom" -> NO_PAINT, damage through the second UV, paint from the texel) draws the damage, rust and
blood sheets exactly as the game does. The 42.21 game only special-cases the exact names vehicle,
vehicle_multiuv and vehicle_norandom_multiuv (ModelManager.modifyShaderName), so the name changes
nothing else for the game.

What is added:
  * a skinned vertex program (the stock reflective shader only ships a static one, so animated
    panels drew nothing on it) - the bone palette code is the stock noreflect vertex program
  * viewDir: the direction to the camera in vehicle space, read off the projection matrix
  * smoothed diffuse: CRV_SMOOTH blends the stock 3-step banding toward plain Lambert
  * Blinn-Phong specular and a Fresnel rim (both off: CRV_SPEC, CRV_RIM)
  * body reflection scaled by a gloss constant, CRV_GLOSS (0.33 = the stock reflection). It was the Mask
    texture's alpha until 2026-10-18: the game premultiplies alpha when it shrinks a sheet to the
    player's texture size, which broke every zone colour (compose_textures: the shipped Mask is RGB)
Run scripts\check_shaders.py afterwards: it compiles the pair on this machine's GPU driver.
"""
import os
import re
import crv_paths as _crv_paths  # noqa: E402  (machine paths: local_paths.json)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(_crv_paths.GAME, "media", "shaders")
OUT = os.path.join(ROOT, "mod", "Contents", "mods", "HondaCRVGen1", "common", "media", "shaders")
# The name must start with "vehicle": ModelManager.setModelMetaData routes a model whose shader
# name startsWithIgnoreCase("vehicle") to the Vehicle Texture Size option (engine default 512) and
# every other shader to the general Texture Size option (default 256). As crvgen1_vehicle the body
# sheet was loaded at 256 px for anyone on the defaults (2026-10-12). gen_scripts.SHADER and
# check_shaders follow this constant. "norandom" in it: Project Viewpoint's NO_PAINT kind (docstring).
NAME = "vehicle_crvgen1_norandom"
FRAG_SOURCE = "vehicle_norandom_multiuv.frag"
HEADER = ("// %s: generated by scripts/gen_shaders.py from Project Zomboid's %s (The Indie Stone).\n"
          "// Additions: viewDir varying, smoothed diffuse, Blinn-Phong specular and rim, body\n"
          "// reflection scaled by a constant gloss. For use in PZ mods only.\n")
VIEW = ("\tviewDir = -normalize(vec3(ModelViewProjection[0][2], ModelViewProjection[1][2], "
        "ModelViewProjection[2][2]));\n")
# Stock lighting since the planar repaint (2026-10-12, spec/planar-texture-plan.md): vanilla and KI5
# keep quantise(dot, 3) exactly and no specular; the painted gradient, seams and highlights carry the
# form, and smoothing or shine on top of them read soft. The hooks stay so a value can be tried in game.
CONSTS = ("\nconst float CRV_SMOOTH = 0.0;   // 0 = stock 3-step banding, 1 = plain Lambert\n"
          "const float CRV_SHINE = 28.0;\n"
          "const float CRV_SPEC = 0.0;\n"
          "const float CRV_RIM = 0.0;\n"
          "const float CRV_GLOSS = 0.33;  // body reflection x (0.5 + 1.5 gloss): 0.33 = the stock reflection\n"
          "const float CRV_TAIL = %.2f;   // combined stop / tail lens: its glow with the tail lights only (brake = 1)\n"
          "const float CRV_MARK = 0.0039;  // Mask blue >= this on a stop zone: the combined lens's stop part (2/255)\n"
          % 0.0)
# Combined stop / tail lamps (bug wave 1, 2026-10-24). The RD1's D-pillar lens is one dual-filament lamp: tail with the
# lights, full on the brake. The game has no zone for that (BaseVehicle lights lights_*t from the tail light parts and
# stop_* from stoplightsOn + battery alone), and a lens split into a tail half and a stop half draws a dark seam at
# every texture size (the shader matches zone colours within 0.01 on a bilinear sample). compose_textures.lamp_guard
# gives each D-pillar lens ONE zone, its side's tail zone; here a tail-zone fragment lights at TAIL_LEVEL of the lit
# lens with the tail lights on, and fully while braking (lights on or off), unless the lamp is uninstalled. The high
# stop lamp (stop zone) and the head lamps keep the stock rule. TextureLightsEnables2[c][r] pairs with texen2[c][r]
# (dommat4): tail R / L = [0][3] / [1][0] (colZone20 / 21), stop R / L = [1][1] / [1][2] (colZone22 / 23).
# Bug wave 3 (H-VP-1, 2026-10-24): Project Viewpoint never runs this shader and lights each zone from the game's
# switches, so the all-tail lens lit only with the lights there (braking in daylight: just the high stop lamp).
# The lens is now its tail part (tail zone) and its stop part (the side's stop zone), separate UV islands far
# enough apart that no capped texel mixes them (bake_atlas LENS_GROUPS, planar_uv.GROUP_GAP): the game's stock
# rule and Viewpoint light the tail part with the lights and the stop part on the brake. The combined rule stays
# here for the look the owner approved (the whole lens glows softly with the lights, fully on the brake): the
# stop part carries Mask blue 2/255 (stop_rc / stop_lc, compose_textures.mark_combined_stop; 0.0078 from the
# stop colour, inside every renderer's 0.01) and lights like the tail part of its side: CRV_TAIL with that
# side's tail light, fully on the brake, grey with that side's tail lamp removed. The high stop lamp (plain
# stop_l) and the head lamps keep t1en.
TAIL_LEVEL = 0.40
MARK_LEVEL = 0.0039                  # CRV_MARK: half the tag's 2/255
CONSTS = CONSTS.replace("%.2f;" % 0.0, "%.2f;" % TAIL_LEVEL)
assert "CRV_MARK = %.4f;" % MARK_LEVEL in CONSTS
LAMP_RULE = ("\t// combined stop / tail lens (gen_shaders TAIL_LEVEL): its tail part (tail zones) and its stop part (a stop zone\n"
             "\t// with Mask blue >= CRV_MARK) glow at CRV_TAIL with their side's tail light, fully while braking, and grey\n"
             "\t// with their side's tail lamp removed; the high stop lamp and the head lamps keep t1en\n"
             "\tfloat crvMark = step(CRV_MARK, texColorMask.z);\n"
             "\tfloat crvCombR = texen2[1][1] * crvMark;\n"
             "\tfloat crvCombL = texen2[1][2] * crvMark;\n"
             "\tt4en = max(t4en, step(0.5, crvCombR * TextureUninstall2[0][3] + crvCombL * TextureUninstall2[1][0]));\n"
             "\tfloat crvTailZone = clamp(texen2[0][3] + texen2[1][0] + crvCombR + crvCombL, 0.0, 1.0);\n"
             "\tfloat crvTailOn = step(0.5, (texen2[0][3] + crvCombR) * TextureLightsEnables2[0][3]"
             " + (texen2[1][0] + crvCombL) * TextureLightsEnables2[1][0]) * (1.0 - t4en);\n"
             "\tfloat crvBrake = step(0.5, TextureLightsEnables2[1][1] + TextureLightsEnables2[1][2]) * (1.0 - t4en);\n"
             "\tfloat crvLamp = mix(t1en, max(CRV_TAIL * crvTailOn, crvBrake), crvTailZone);\n")


def read(name):
    return open(os.path.join(GAME, name), encoding="utf-8-sig").read().replace("\r\n", "\n")


def must(s, old, new):
    assert old in s, "anchor missing in the game source: %r" % old
    return s.replace(old, new, 1)


def build():
    # static vertex program: stock + viewDir
    st = read("vehicle_multiuv_static.vert")
    st = must(st, "varying vec4 positionEye;\n", "varying vec4 positionEye;\nvarying vec3 viewDir;\n")
    st = must(st, "\tvertColour = vec3(1,1,1);\n", "\tvertColour = vec3(1,1,1);\n" + VIEW)
    st = must(st, "#version 330\n", "#version 330\n" + HEADER % (NAME + "_static.vert", "vehicle_multiuv_static.vert"))
    # skinned vertex program: stock noreflect skinning + positionEye (as the static one computes it) + viewDir
    sk = read("vehicle_multiuv_noreflect.vert")
    sk = must(sk, "varying vec2 texCoords1;\n", "varying vec2 texCoords1;\nvarying vec4 positionEye;\nvarying vec3 viewDir;\n")
    sk = must(sk, "\tvertColour = vec3(1.0,1.0,1.0);\n",
              "\tvertColour = vec3(1.0,1.0,1.0);\n"
              "\tpositionEye = (ModelViewProjection * boneEffect * position) - vec4(-0.2, 0.2, 0.2, 0);\n" + VIEW)
    sk = must(sk, "#version 330\n", "#version 330\n" + HEADER % (NAME + ".vert", "vehicle_multiuv_noreflect.vert"))
    # fragment program: stock (norandom) + gloss, specular, rim, softened banding
    fr = read(FRAG_SOURCE)
    fr = must(fr, "\tvec3 paintColor = rgb2hsv(tex.rgb).xyz;\n", "\tvec3 paintColor = rgb2hsv(tex.rgb).xyz;\n")
    assert "TexturePainColor.x" not in fr and "TexturePainColor.y" not in fr, "the norandom source reads the random paint"
    fr = must(fr, "varying vec4 positionEye;\n", "varying vec4 positionEye;\nvarying vec3 viewDir;\n" + CONSTS)
    fr = must(fr, "\tvec4 texColorMask = texture2D(TextureMask, texCoords);\n",
              "\tvec4 texColorMask = texture2D(TextureMask, texCoords);\n"
              "\tfloat gloss = CRV_GLOSS;\n"
              "\tvec3 spec = vec3(0.0);\n")
    n = fr.count("\tquantise(dotprod, 3.0);\n")
    assert n == 5, n
    fr = fr.replace("\tquantise(dotprod, 3.0);\n",
                    "\t{ float q = dotprod; quantise(q, 3.0); dotprod = mix(q, dotprod, CRV_SMOOTH); }\n")
    fr, n = re.subn(r"\tlighting \+= Light(\d)Colour \* dotprod;\n",
                    lambda m: m.group(0) + ("\tspec += Light%sColour * pow(max(dot(normal, normalize(normalize(Light%sDirection) + viewDir)), 0.0), CRV_SHINE);\n" % (m.group(1), m.group(1))),
                    fr)
    assert n == 5, n
    # open or removed glass: the game flags the window zone like an uninstalled part and the stock
    # shader paints it flat grey (the "floating grey square"); drop those fragments instead
    fr = must(fr, "\tfloat noTintAlpha = clamp(windowAlpha + frontAlpha + tailAlpha, 0.0, 1.0);\n",
              "\tfloat noTintAlpha = clamp(windowAlpha + frontAlpha + tailAlpha, 0.0, 1.0);\n"
              "\tif (t4en > 0.5 && windowAlpha > 0.5) discard;\n")
    fr = must(fr, "\tfloat t4en = step(0.5, dommat4(texen1, TextureUninstall1) + dommat4(texen2, TextureUninstall2) );\n",
              "\tfloat t4en = step(0.5, dommat4(texen1, TextureUninstall1) + dommat4(texen2, TextureUninstall2) );\n" + LAMP_RULE)
    fr = must(fr, "\tcol = mix(col, texColorLights.xyz, texColorLights.a*t1en);\n",
              "\tcol = mix(col, texColorLights.xyz, texColorLights.a*crvLamp);\n")
    fr = must(fr, "(1.0-ref_en)*(0.05 + ReflectionParam.z*0.3)", "(1.0-ref_en)*(0.05 + ReflectionParam.z*0.3)*(0.5 + 1.5*gloss)")
    fr = must(fr, "\tcol *= lighting * TintColourNew;\n",
              "\tcol *= lighting * TintColourNew;\n\n"
              "\tfloat fres = pow(1.0 - max(dot(normal, viewDir), 0.0), 3.0);\n"
              "\tcol += (spec * CRV_SPEC + fres * CRV_RIM * lighting) * gloss * TintColourNew * (1.0 - t4en);\n")
    fr = must(fr, "#version 120\n", "#version 120\n" + HEADER % (NAME + ".frag", FRAG_SOURCE))
    os.makedirs(OUT, exist_ok=True)
    for fn, text in ((NAME + "_static.vert", st), (NAME + ".vert", sk), (NAME + ".frag", fr)):
        with open(os.path.join(OUT, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("WROTE", fn, len(text.splitlines()), "lines")
    # an earlier name's files would ship as dead weight (and a stale copy confuses the next reader)
    for fn in sorted(os.listdir(OUT)):
        if fn.startswith("vehicle_crvgen1") and not fn.startswith(NAME + ".") and not fn.startswith(NAME + "_static."):
            os.remove(os.path.join(OUT, fn))
            print("REMOVED", fn)


if __name__ == "__main__":
    build()
